#!/usr/bin/env node
'use strict';

/**
 * Generates the browser-safe word lists used by Shadle.
 *
 * Input files and the plaintext daily schedule stay local and are ignored by
 * Git. The generated browser file contains SHA-1 digests only: answer digests
 * are shuffled for the daily schedule and allowed-guess digests include both
 * input lists.
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const wordListDirectory = path.join(root, 'wordlists');
const answerFile = path.join(wordListDirectory, 'answers.txt');
const allowedFile = path.join(wordListDirectory, 'allowed-guesses.txt');
const scheduleFile = path.join(wordListDirectory, 'daily-answers-shuffled.txt');
const outputFile = path.join(root, 'words.js');
const startDate = new Date('2024-01-01T00:00:00Z');

function readWords(file) {
  const words = fs.readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .map(word => word.trim().toLowerCase())
    .filter(Boolean);

  const invalid = words.find(word => !/^[a-z]{5}$/.test(word));
  if (invalid) throw new Error(`${path.basename(file)} contains an invalid word: ${invalid}`);
  if (new Set(words).size !== words.length) {
    throw new Error(`${path.basename(file)} contains duplicate words.`);
  }
  return words;
}

function shuffle(words) {
  const shuffled = [...words];
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = crypto.randomInt(index + 1);
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }
  return shuffled;
}

function sha1(word) {
  return crypto.createHash('sha1').update(word).digest('hex');
}

function getDayNumber() {
  const now = new Date();
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  return Math.max(0, Math.floor((today - startDate.getTime()) / 86_400_000));
}

function formatArray(name, hashes) {
  const lines = [];
  for (let index = 0; index < hashes.length; index += 5) {
    lines.push(`  ${hashes.slice(index, index + 5).map(hash => `'${hash}'`).join(', ')},`);
  }
  return `window.${name} = [\n${lines.join('\n')}\n];`;
}

const answers = readWords(answerFile);
const allowedGuesses = readWords(allowedFile);
const answerSet = new Set(answers);
const overlap = allowedGuesses.filter(word => answerSet.has(word));
if (overlap.length) {
  throw new Error('Allowed guesses must not duplicate answer words.');
}

const shuffledAnswers = shuffle(answers);
const answerHashes = shuffledAnswers.map(sha1);
const allowedGuessHashes = [...new Set([...answers, ...allowedGuesses])].map(sha1).sort();
const source = `'use strict';\n\n/**\n * Generated by scripts/generate-word-lists.js. Do not edit manually.\n * Source word files are intentionally local-only; this file has SHA-1 digests only.\n */\n${formatArray('ANSWER_HASHES', answerHashes)}\n\n${formatArray('ALLOWED_GUESS_HASHES', allowedGuessHashes)}\n`;

fs.writeFileSync(outputFile, source);
fs.writeFileSync(scheduleFile, `${shuffledAnswers.join('\n')}\n`);

const dayNumber = getDayNumber();
console.log(`Generated ${path.relative(root, outputFile)} with ${answers.length} daily answers and ${allowedGuessHashes.length} allowed guesses.`);
console.log(`Wrote plaintext daily schedule to ${path.relative(root, scheduleFile)}.`);
console.log(`Today's answer (Day ${dayNumber + 1}): ${shuffledAnswers[dayNumber % shuffledAnswers.length]}`);
